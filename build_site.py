def render_page(page: Page, pages: list[Page], home: Page, roots, res: Resolver) -> str:
    if page.kind == "csv":
        raw = html.escape(posixpath.basename(page.src))
        body = (f"<h1>{html.escape(page.name)}</h1>"
                f'<p><a class="dl" href="{raw}" download>Download CSV</a> '
                f'<a class="dl" href="{REPO_URL}/blob/{BRANCH}/{page.src}">View on GitHub</a></p>'
                + csv_html(ROOT / page.src))
        meta, art_cls, art_style = "", "", ""
    else:
        body = md_to_html(page.text)
        body = res.rewrite(page, body)
        body = PROJECT_MARKER_RE.sub(lambda _m: project_table(pages, page), body)
        meta = render_meta(page, res)
        if page.msg:
            art_cls, art_style = "msg", f' style="--h:{hue(page.meta.get("from", page.msg.group(2)))}"'
        else:
            art_cls, art_style = "", ""
    footer = (f'<a href="{REPO_URL}/blob/{BRANCH}/{page.src}">View source on GitHub</a> · '
              f"Generated from Markdown by build_site.py")
    values = {
        "MARK": MARK, "TITLE": html.escape(page.title if page.kind == "md" else page.name),
        "SITE": SITE_NAME, "CSS": CSS, "JS": JS,
        "HOME": html.escape(rel_link(page.out, home.out)),
        "TREE": render_tree(home, roots, page),
        "CRUMBS": breadcrumbs(page, home, res),
        "ARTCLASS": art_cls, "ARTSTYLE": art_style, "META": meta, "BODY": body,
        "PAGER": pager(page, pages), "FOOTER": footer,
    }
    out = PAGE_TMPL
    for k, v in values.items():
        out = out.replace(f"%%{k}%%", v)
    return out


# --------------------------------------------------------------------------- main
def clean() -> None:
    shutil.rmtree(SITE, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only report problems, write nothing")
    args = ap.parse_args()

    pages = collect()
    home = next((p for p in pages if p.section == "home"), None)
    if not home:
        print("docs/README.md is missing", file=sys.stderr)
        return 1
    home_tree, roots = build_tree(pages)
    res = Resolver(pages)

    rendered = {p.out: render_page(p, pages, home, roots, res) for p in pages}
    for w in sorted(set(res.warnings)):
        print("warning:", w, file=sys.stderr)

    if args.check:
        print(f"checked {len(pages)} pages, {len(set(res.warnings))} warning(s)")
        return 0

    clean()
    for p in pages:
        dest = SITE / p.out
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(rendered[p.out], encoding="utf-8")
        if p.kind == "csv":
            shutil.copyfile(ROOT / p.src, SITE / p.src)
    (SITE / ".nojekyll").touch()
    print(f"built {len(pages)} pages into _site/ ({len(set(res.warnings))} warning(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
