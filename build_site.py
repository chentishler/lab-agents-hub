ROOT = Path(__file__).resolve().parent
DOCS = ROOT / "docs"
SITE = ROOT / "_site"
SITE_NAME = "Lab Agents Hub"
REPO_URL = "https://github.com/chentishler/lab-agents-hub"
BRANCH = "main"
MARK = "<!-- generated by build_site.py: do not edit -->"

MSG_TYPES = ["proposal", "reply", "question", "data", "critique", "final-proposal",
             "agreed", "objection", "human-note", "escalation"]
MSG_RE = re.compile(r"^(\d{3})-(.+?)-(" + "|".join(sorted(MSG_TYPES, key=len, reverse=True)) + r")\.md$")
PRIORITY = {"README.md": 0, "BRIEF.md": 1, "STATUS.md": 2, "SOLUTION.md": 3,
            "HUMANS.md": 10, "AGENTS.md": 11, "PROTOCOL.md": 12, "PROMPTS.md": 13}
AGENT_KEYS = {"from", "to", "agents", "next", "updated_by", "written_by"}
META_ORDER = ["from", "to", "type", "status", "round", "next", "date", "updated", "updated_by",
              "re", "data", "agents", "max_rounds", "created", "written_by"]
STATUS_HUE = {"active": 210, "needs-reply": 210, "solved": 150, "agreed": 150,
              "solved-pending-human-review": 38, "waiting-human": 22, "blocked": 4,
              "paused": 220, "draft": 220, "info-only": 220}

FM_RE = re.compile(r"\A---[ \t]*\n(.*?)\n---[ \t]*\n", re.S)
H1_RE = re.compile(r"^#\s+(.+?)\s*$", re.M)
HREF_RE = re.compile(r'href="([^"]*)"')
PROJECT_MARKER_RE = re.compile(r"(?:<p>)?<!-- PROJECT_TABLE -->(?:</p>)?")


@dataclass
class Page:
    src: str      # posix path relative to the repo root
    kind: str     # "md" or "csv"
    out: str      # posix path relative to docs/
    section: str  # home | guides | templates | projects
    meta: dict
    text: str
    h1: str

    @property
    def name(self) -> str:
        return posixpath.basename(self.src)

    @property
    def dir(self) -> str:
        return posixpath.dirname(self.src)

    @property
    def title(self) -> str:
        return self.meta.get("title") or self.h1 or prettify(self.name)

    @property
    def msg(self):
        return MSG_RE.match(self.name) if self.kind == "md" else None

    @property
    def label(self) -> str:
        m = self.msg
        if m:
            return f"{m.group(1)} · {m.group(2)} · {m.group(3)}"
        if self.kind == "csv" or (self.section == "templates" and self.name != "README.md"):
            return self.name
        return self.h1 or self.meta.get("title") or prettify(self.name)


# --------------------------------------------------------------------------- helpers
def prettify(name: str) -> str:
    name = re.sub(r"\.(md|csv)$", "", name)
    s = name.replace("-", " ").replace("_", " ")
    return s[:1].upper() + s[1:]


def split_front(text: str):
    m = FM_RE.match(text)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.lstrip().startswith("#"):
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, text[m.end():]


def out_for(src: str) -> str:
    rel = src[len("docs/"):] if src.startswith("docs/") else src
    p = posixpath.splitext(rel)
    if p[1] == ".md":
        if posixpath.basename(rel) == "README.md":
            return posixpath.join(posixpath.dirname(rel), "index.html")
        return p[0] + ".html"
    return rel + ".html"  # csv


def section_of(src: str) -> str:
    if src.startswith("projects/"):
        return "projects"
    rel = src[len("docs/"):]
    if rel == "README.md":
        return "home"
    if rel.startswith("templates/"):
        return "templates"
    return "guides"


def rel_link(from_out: str, to_out: str) -> str:
    return posixpath.relpath(to_out, posixpath.dirname(from_out) or ".")


def hue(s: str) -> int:
    return sum(ord(c) * (i + 1) for i, c in enumerate(s)) % 360


# --------------------------------------------------------------------------- collect
def collect() -> list[Page]:
    pages: list[Page] = []
    for base in (DOCS, ROOT / "projects"):
        if not base.exists():
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file() or p.name.startswith("."):
                continue
            src = p.relative_to(ROOT).as_posix()
            is_docs = src.startswith("docs/")
            if p.suffix == ".md":
                text = p.read_text(encoding="utf-8")
                meta, body = split_front(text)
                m = H1_RE.search(body)
                pages.append(Page(src, "md", out_for(src), section_of(src), meta, body,
                                  m.group(1).strip() if m else ""))
            elif p.suffix == ".csv" and not is_docs:
                pages.append(Page(src, "csv", out_for(src), "projects", {}, "", p.name))
    return pages


# --------------------------------------------------------------------------- sidebar tree
class Node:
    def __init__(self, name: str):
        self.name = name
        self.children: dict[str, "Node"] = {}
        self.index: Page | None = None
        self.brief: Page | None = None
        self.files: list[Page] = []
        self.srcs: set[str] = set()


def build_tree(pages: list[Page]):
    roots = {k: Node(k) for k in ("guides", "templates", "projects")}
    home = None
    for pg in pages:
        if pg.section == "home":
            home = pg
            continue
        parts = pg.src.split("/")
        parts = parts[1:] if pg.section in ("projects", "guides") else parts[2:]
        node = roots[pg.section]
        node.srcs.add(pg.src)
        for d in parts[:-1]:
            node = node.children.setdefault(d, Node(d))
            node.srcs.add(pg.src)
        if pg.name == "README.md" and pg.kind == "md":
            node.index = pg
        elif pg.name == "BRIEF.md" and pg.section == "projects":
            node.brief = pg
        else:
            node.files.append(pg)
    return home, roots


def entry_key(kind: str, item) -> tuple:
    if kind == "file":
        return (0, PRIORITY.get(item.name, 50), item.name)
    return (1, 0, item.name)


def render_tree(home: Page, roots: dict[str, Node], cur: Page) -> str:
    def a(pg: Page, text: str, extra: str = "") -> str:
        active = pg.src == cur.src
        cls = f' class="active{extra}"' if active else (f' class="{extra.strip()}"' if extra.strip() else "")
        cur_attr = ' aria-current="page"' if active else ""
        return f'<a href="{html.escape(rel_link(cur.out, pg.out))}"{cls}{cur_attr}>{html.escape(text)}</a>'

    def render_node(node: Node, label: str, force_open: bool = False) -> str:
        idx = node.index or node.brief
        text = label or (idx.meta.get("title") if idx else None) or \
            (idx.h1 if idx else None) or prettify(node.name)
        is_open = force_open or cur.src in node.srcs
        head = a(idx, text) if idx else f"<span>{html.escape(text)}</span>"
        entries = [("file", f) for f in node.files]
        if node.index and node.brief:
            entries.append(("file", node.brief))
        entries += [("dir", c) for c in node.children.values()]
        entries.sort(key=lambda e: entry_key(*e))
        items = []
        for kind, item in entries:
            if kind == "file":
                items.append(f'<li class="file">{a(item, item.label)}</li>')
            else:
                items.append(render_node(item, ""))
        cls = "folder open" if is_open else "folder"
        return (f'<li class="{cls}"><div class="row"><button class="caret" type="button" '
                f'aria-label="Expand or collapse"></button>{head}</div><ul>{"".join(items)}</ul></li>')

    parts = []
    if home:
        parts.append(f'<div class="sec"><div class="sec-h">{a(home, "Home")}</div></div>')
    for key, title in (("guides", "Guides"), ("projects", "Projects"), ("templates", "Templates")):
        node = roots[key]
        if not node.srcs:
            continue
        idx = node.index
        head = a(idx, title) if idx else html.escape(title)
        entries = [("file", f) for f in node.files] + [("dir", c) for c in node.children.values()]
        entries.sort(key=lambda e: entry_key(*e))
        items = []
        for kind, item in entries:
            items.append(f'<li class="file">{a(item, item.label)}</li>' if kind == "file"
                         else render_node(item, ""))
        parts.append(f'<div class="sec"><div class="sec-h">{head}</div>'
                     f'<ul class="tree">{"".join(items)}</ul></div>')
    return "\n".join(parts)


# --------------------------------------------------------------------------- links
class Resolver:
    def __init__(self, pages: list[Page]):
        self.by_src = {p.src: p for p in pages}
        self.dir_index: dict[str, Page] = {}
        for p in pages:
            if p.kind == "md" and p.name in ("README.md", "BRIEF.md"):
                if p.name == "BRIEF.md" and p.section != "projects":
                    continue
                if p.name == "README.md" or p.dir not in self.dir_index:
                    self.dir_index[p.dir] = p
        self.warnings: list[str] = []

    def target(self, page: Page, href: str):
        """Return (Page|None, path_in_repo, fragment) for a relative href."""
        path, _, frag = href.partition("#")
        path = path.partition("?")[0]
        if not path:
            return None, "", frag
        tgt = posixpath.normpath(posixpath.join(page.dir, unquote(path)))
        if path.endswith("/") or (ROOT / tgt).is_dir():
            return self.dir_index.get(tgt), tgt, frag
        return self.by_src.get(tgt), tgt, frag

    def rewrite(self, page: Page, body: str) -> str:
        def sub(m: re.Match) -> str:
            href = m.group(1)
            if re.match(r"^(?:[a-z][a-z0-9+.-]*:|#|//|/)", href, re.I):
                return m.group(0)
            pg, tgt, frag = self.target(page, html.unescape(href))
            if pg:
                new = rel_link(page.out, pg.out) + (f"#{frag}" if frag else "")
                return f'href="{html.escape(new)}"'
            if (ROOT / tgt).exists():
                return f'href="{REPO_URL}/blob/{BRANCH}/{tgt}"'
            self.warnings.append(f"{page.src}: broken link '{href}'")
            return m.group(0)
        return HREF_RE.sub(sub, body)

    def meta_link(self, page: Page, value: str) -> str | None:
        for base in (page.dir, posixpath.dirname(page.dir)):
            tgt = posixpath.normpath(posixpath.join(base, value))
            pg = self.by_src.get(tgt)
            if pg:
                return rel_link(page.out, pg.out)
        return None


# --------------------------------------------------------------------------- page parts
def agent_chip(name: str) -> str:
    return (f'<span class="chip agent" style="--h:{hue(name)}"><i class="dot"></i>'
            f'{html.escape(name)}</span>')


def status_badge(value: str) -> str:
    h = STATUS_HUE.get(value, 220)
    s = "12%" if value in ("paused", "draft", "info-only") else "55%"
    return f'<span class="chip badge" style="--h:{h};--s:{s}">{html.escape(value)}</span>'


def render_meta(page: Page, res: Resolver) -> str:
    if page.section != "projects" or page.kind != "md":
        return ""
    meta = dict(page.meta)
    if page.name == "BRIEF.md":  # STATUS.md is the live source of truth for status
        st = res.by_src.get(page.dir + "/STATUS.md")
        if st and st.meta.get("status"):
            meta["status"] = st.meta["status"]
    keys = [k for k in meta if k not in ("title", "demo")]
    if not keys:
        return ""
    keys.sort(key=lambda k: (META_ORDER.index(k) if k in META_ORDER else 99, k))
    rows = []
    for k in keys:
        v = meta[k]
        vals = [x.strip() for x in v.split(",") if x.strip()] if k in AGENT_KEYS | {"to", "data"} else [v]
        if k in AGENT_KEYS:
            cell = " ".join(agent_chip(x) if x != "any" and x != "all" else
                            f'<span class="chip">{x}</span>' for x in vals)
        elif k == "status":
            cell = status_badge(v)
        elif k in ("re", "data"):
            bits = []
            for x in vals:
                link = res.meta_link(page, x)
                bits.append(f'<a class="chip" href="{html.escape(link)}">{html.escape(x)}</a>' if link
                            else f'<span class="chip">{html.escape(x)}</span>')
            cell = " ".join(bits)
        else:
            cell = f'<span class="chip">{html.escape(v)}</span>'
        rows.append(f"<div><dt>{html.escape(k)}</dt><dd>{cell}</dd></div>")
    demo = '<span class="chip badge" style="--h:280;--s:45%">demo · synthetic data</span>' \
        if page.meta.get("demo") == "true" else ""
    if demo:
        rows.append(f"<div>{demo}</div>")
    return f'<dl class="meta">{"".join(rows)}</dl>'


def project_table(pages: list[Page], page: Page) -> str:
    by_dir = {}
    for p in pages:
        by_dir.setdefault(p.dir, []).append(p)
    rows = []
    for brief in sorted((p for p in pages if p.name == "BRIEF.md" and p.section == "projects"),
                        key=lambda p: p.src):
        d = brief.dir
        status_pg = next((p for p in by_dir.get(d, []) if p.name == "STATUS.md"), None)
        status = (status_pg.meta.get("status") if status_pg else None) or brief.meta.get("status") or "draft"
        n_msg = sum(1 for p in by_dir.get(d + "/messages", []) if p.kind == "md")
        agents = ", ".join(a.strip() for a in brief.meta.get("agents", "").split(",") if a.strip())
        updated = (status_pg.meta.get("updated") if status_pg else None) or brief.meta.get("created", "")
        demo = ' <span class="chip badge" style="--h:280;--s:45%">demo</span>' \
            if brief.meta.get("demo") == "true" else ""
        link = html.escape(rel_link(page.out, brief.out))
        path = d[len("projects/"):]
        rows.append(f'<tr><td><a href="{link}">{html.escape(brief.title)}</a>{demo}'
                    f'<br><small class="muted">{html.escape(path)}</small></td>'
                    f"<td>{status_badge(status)}</td><td>{html.escape(agents)}</td>"
                    f"<td>{n_msg}</td><td>{html.escape(updated)}</td></tr>")
    if not rows:
        return "<p><em>No projects yet. Start one with the template.</em></p>"
    head = "<tr><th>Project</th><th>Status</th><th>Agents</th><th>Messages</th><th>Updated</th></tr>"
    return f'<div class="tbl"><table class="projects"><thead>{head}</thead><tbody>{"".join(rows)}</tbody></table></div>'


def breadcrumbs(page: Page, home: Page, res: Resolver) -> str:
    if page.src == home.src:
        return ""
    out =[f'<a href="{html.escape(rel_link(page.out, home.out))}">Home</a>']
    parts = page.src.split("/")[:-1]
    start = 1 if parts and parts[0] == "docs" else 0
    for i in range(start, len(parts)):
        d = "/".join(parts[: i + 1])
        if d == "docs":
            continue
        idx = res.dir_index.get(d)
        if idx and idx.src == page.src:
            continue
        label = (idx.title if idx else None) or prettify(parts[i])
        if idx:
            out.append(f'<a href="{html.escape(rel_link(page.out, idx.out))}">{html.escape(label)}</a>')
        else:
            out.append(f"<span>{html.escape(label)}</span>")
    out.append(f"<span>{html.escape(page.label if page.msg or page.kind == 'csv' else page.title)}</span>")
    return '<nav class="crumbs">' + '<i>›</i>'.join(out) + "</nav>"


def pager(page: Page, pages: list[Page]) -> str:
    if not page.msg:
        return ""
    sibs = sorted((p for p in pages if p.dir == page.dir and p.msg), key=lambda p: p.name)
    i = next((k for k, p in enumerate(sibs) if p.src == page.src), None)
    if i is None:
        return ""
    prev = (f'<a class="prev" href="{html.escape(rel_link(page.out, sibs[i-1].out))}">'
            f'<small>Previous</small>{html.escape(sibs[i-1].label)}</a>') if i > 0 else "<span></span>"
    nxt = (f'<a class="next" href="{html.escape(rel_link(page.out, sibs[i+1].out))}">'
           f'<small>Next</small>{html.escape(sibs[i+1].label)}</a>') if i < len(sibs) - 1 else "<span></span>"
    return f'<div class="pager">{prev}{nxt}</div>'


def csv_html(path: Path) -> str:
    with path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.reader(fh))
    if not rows:
        return "<p><em>Empty file.</em></p>"
    cap = 500
    head, body = rows[0], rows[1:cap + 1]
    th = "".join(f"<th>{html.escape(c)}</th>" for c in head)
    tr = "".join("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in r) + "</tr>" for r in body)
    note = f'<p class="muted"><small>Showing the first {cap} of {len(rows)-1} rows.</small></p>' \
        if len(rows) - 1 > cap else f'<p class="muted"><small>{len(rows)-1} rows, {len(head)} columns.</small></p>'
    return f'<div class="tbl"><table class="data"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>{note}'


def md_to_html(text: str) -> str:
    md = markdown.Markdown(extensions=["tables", "fenced_code", "toc", "sane_lists", "attr_list"])
    body = md.convert(text)
    body = body.replace("<table>", '<div class="tbl"><table>').replace("</table>", "</table></div>")
    return body


